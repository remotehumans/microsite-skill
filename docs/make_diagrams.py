# ABOUTME: Writes the guide's plain-English diagrams as HTML/SVG in docs/: the big picture, what happens to each company, and the outreach steps.
# ABOUTME: Usage: python3 docs/make_diagrams.py, then export each to docs/images/<name>.png (README, "Rebuilding the diagrams").
from html import escape
from pathlib import Path

DOCS = Path(__file__).resolve().parent
SANS = "'Helvetica Neue', Helvetica, Arial, sans-serif"
MONO = "'Courier Prime', monospace"
SERIF = "'Crimson Pro', Georgia, serif"
INK, BODY, MUTED, ACCENT = "#141414", "#4a4a4a", "#6b6b6b", "#E04F18"
SOFT, TINT, RULE = "#f4f4f2", "rgba(224,79,24,0.10)", "rgba(20,20,20,0.16)"


def text(x, y, rows, size=12.5, fill=BODY, dy=17, weight=400, family=SANS, anchor="start"):
    return (f'<text x="{x}" y="{y}" font-family="{family}" font-size="{size}" font-weight="{weight}" fill="{fill}" text-anchor="{anchor}">'
            + "".join(f'<tspan x="{x}" dy="{0 if i == 0 else dy}">{escape(r)}</tspan>' for i, r in enumerate(rows)) + "</text>")


def bullets(items):
    """One bullet per item when a box holds more than one thing; an item's later lines are indented."""
    many = len(items) > 1
    return [("• " if many and j == 0 else "  " if many else "") + line for item in items for j, line in enumerate(item)]


def eyebrow(x, y, label, fill=MUTED):
    return f'<text x="{x}" y="{y}" font-family="{MONO}" font-size="9" letter-spacing="0.16em" fill="{fill}">{escape(label)}</text>'


def box(x, y, w, h, kind="step"):
    style = {"step": ('#ffffff', INK, 1.2), "focal": (TINT, ACCENT, 1.5), "in": (SOFT, RULE, 1), "out": ('#ffffff', "rgba(20,20,20,0.55)", 1)}[kind]
    return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="6" fill="{style[0]}" stroke="{style[1]}" stroke-width="{style[2]}"/>'


def arrow(x1, y1, x2, y2):
    return f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}"/>'


def page(name, title, desc, w, h, body):
    html = f'''<!DOCTYPE html>
<!-- ABOUTME: {escape(desc)} -->
<!-- ABOUTME: Generated by docs/make_diagrams.py (Ell Dog Times diagram profile); exported to docs/images/{name}.png for the README. -->
<html lang="en-GB">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>{escape(title)}</title>
  <link href="https://fonts.googleapis.com/css2?family=Crimson+Pro:ital,wght@0,400;0,500;1,400&family=Courier+Prime:wght@400;700&display=swap" rel="stylesheet">
  <style>
    *, *::before, *::after {{ box-sizing: border-box; margin: 0; padding: 0; }}
    body {{ font-family: {SANS}; background: #ffffff; color: {INK}; }}
    svg {{ width: {w}px; display: block; }}
  </style>
</head>
<body>
  <svg id="diagram" viewBox="0 0 {w} {h}" xmlns="http://www.w3.org/2000/svg" role="img" aria-labelledby="t d">
    <title id="t">{escape(title)}</title>
    <desc id="d">{escape(desc)}</desc>
    <defs><marker id="arrow" markerWidth="8" markerHeight="6" refX="7" refY="3" orient="auto"><polygon points="0 0, 8 3, 0 6" fill="{BODY}"/></marker></defs>
    <rect width="100%" height="100%" fill="#ffffff"/>
    {body}
  </svg>
</body>
</html>
'''
    (DOCS / f"{name}.html").write_text(html)
    return name


def columns(name, title, desc, intro, steps, focal, footer):
    """Steps across the top; under each, what goes in and what comes out."""
    w, x0, bw, gap = 1200, 16, 168, 32
    st_y, st_h, in_y, in_h, out_y, out_h = 64, 76, 180, 108, 328, 108
    parts, arrows = [], []
    for i in range(len(steps)):
        cx = x0 + i * (bw + gap) + bw // 2
        arrows += [arrow(cx, st_y + st_h, cx, in_y - 2), arrow(cx, in_y + in_h, cx, out_y - 2)]
        if i < len(steps) - 1:
            x = x0 + i * (bw + gap) + bw
            arrows.append(arrow(x, st_y + st_h // 2, x + gap - 2, st_y + st_h // 2))
    parts.append(f'<g stroke="{BODY}" stroke-width="1.5" fill="none" marker-end="url(#arrow)">' + "".join(arrows) + "</g>")
    for i, (label, ins, outs) in enumerate(steps):
        x, is_focal = x0 + i * (bw + gap), label == focal
        parts += [box(x, in_y, bw, in_h, "in"), eyebrow(x + 14, in_y + 20, "GOES IN"), text(x + 14, in_y + 40, bullets(ins))]
        parts += [box(x, st_y, bw, st_h, "focal" if is_focal else "step"), eyebrow(x + 14, st_y + 24, f"STEP {i + 1}", ACCENT if is_focal else MUTED)]
        parts.append(text(x + 14, st_y + 52, [label], size=16.5, fill=INK, weight=600))
        parts += [box(x, out_y, bw, out_h, "out"), eyebrow(x + 14, out_y + 20, "COMES OUT"), text(x + 14, out_y + 40, bullets(outs), fill=INK)]
    parts.append(f'<text x="16" y="40" font-family="{MONO}" font-size="11" letter-spacing="0.18em" fill="{MUTED}">{escape(intro)}</text>')
    parts.append(text(16, 480, footer, size=20, fill=INK, family=SERIF, dy=28))
    return page(name, title, desc, w, 540, "".join(parts))


def big_picture():
    """Two lanes, you and your AI, with five numbered steps that zigzag between them, so who does what is the first thing read."""
    w, h, label_w, bw, bh, gap = 1340, 600, 120, 200, 160, 40
    lanes = {"you": (72, 210), "ai": (298, 210)}  # top y and height of each lane
    steps = [
        ("you", "Pick who", ["A job, a company, or", "\"find me 200 firms…\""], "step"),
        ("ai", "Research them", ["Can they pay? Why now?", "Who decides?"], "step"),
        ("ai", "Build their page", ["In their own colours,", "fonts and photos"], "focal"),
        ("you", "Review it", ["In your gallery: approve", "or ask for changes"], "step"),
        ("you", "Reach out", ["LinkedIn, a Loom, a note,", "then a call"], "step"),
    ]
    parts = []
    # Lane bands and their names, large enough to read first.
    for key, name, fill in (("you", "You", SOFT), ("ai", "Your AI", "rgba(224,79,24,0.06)")):
        y, lh = lanes[key]
        parts.append(f'<rect x="16" y="{y}" width="{w - 32}" height="{lh}" rx="8" fill="{fill}"/>')
        parts.append(text(36, y + lh // 2 + 9, [name], size=26, fill=ACCENT if key == "ai" else INK, weight=700))
    xs = [label_w + 16 + k * (bw + gap) for k in range(len(steps))]
    ys = {key: y + (lh - bh) // 2 for key, (y, lh) in lanes.items()}
    # Arrows first, so boxes sit on top: straight within a lane, one rounded elbow between lanes.
    arrows = []
    for k in range(len(steps) - 1):
        a, b = steps[k][0], steps[k + 1][0]
        x1, x2 = xs[k], xs[k + 1]
        if a == b:
            yy = ys[a] + bh // 2
            arrows.append(f"M{x1 + bw} {yy} H{x2 - 4}")
        else:
            cx, ty = x1 + bw // 2, ys[b] + bh // 2
            start = ys[a] + bh if b == "ai" else ys[a]
            turn = 8 if b == "ai" else -8
            arrows.append(f"M{cx} {start} V{ty - turn} Q{cx} {ty} {cx + 8} {ty} H{x2 - 4}")
    parts.append(f'<g stroke="{BODY}" stroke-width="2" fill="none" marker-end="url(#arrow)">' + "".join(f'<path d="{d}"/>' for d in arrows) + "</g>")
    for k, (lane, title, rows, kind) in enumerate(steps):
        x, y = xs[k], ys[lane]
        parts.append(box(x, y, bw, bh, kind))
        parts.append(f'<circle cx="{x + 34}" cy="{y + 34}" r="16" fill="{ACCENT if kind == "focal" else INK}"/>')
        parts.append(text(x + 34, y + 40, [str(k + 1)], size=17, fill="#ffffff", weight=700, anchor="middle"))
        parts.append(text(x + 20, y + 86, [title], size=21, fill=INK, weight=700))
        parts.append(text(x + 20, y + 116, rows, size=15, fill=BODY, dy=20))
    parts.append(text(16, 40, ["How the microsite skill works"], size=26, fill=INK, family=SERIF))
    parts.append(text(16, h - 30, ["Your AI does the research and the building. Nothing is published or sent until you say so."], size=19, fill=INK, family=SERIF))
    return page("the-big-picture", "The microsite skill: who does what",
                "Two lanes, you and your AI. You pick who; your AI researches them and builds their page; you review it in your gallery and reach out.",
                w, h, "".join(parts))


